#!/usr/bin/env tsx

import fs from "node:fs";
import path from "node:path";
import type { Address } from "viem";

interface DeployedAddresses {
  [contractKey: string]: Address;
}

interface NetworkConfig {
  chainId: string;
  networkName: string;
  addresses: DeployedAddresses;
}

interface ContractABI {
  contractName: string;
  abi: any[];
  sourceName: string;
}

interface GeneratedExports {
  addresses: {
    [networkName: string]: DeployedAddresses;
  };
  abis: {
    [contractName: string]: any[];
  };
  networks: {
    [chainId: string]: string; // chainId -> networkName mapping
  };
}

/**
 * Extracts contract name from Ignition deployment key
 * e.g., "ETSAccessControls#ETSAccessControls" -> "ETSAccessControls"
 * e.g., "ETSAccessControls#ETSAccessControlsProxy" -> "ETSAccessControlsProxy"
 */
function extractContractName(deploymentKey: string): string {
  return deploymentKey.split("#")[1] || deploymentKey;
}

/**
 * Maps chain ID to network name based on our multiChainConfig
 */
function getNetworkName(chainId: string): string {
  switch (chainId) {
    case "31337":
      return "localhost";
    case "84532":
      return "basesepolia";
    default:
      return `chain-${chainId}`;
  }
}

/**
 * Reads Ignition deployment files and generates TypeScript exports
 */
function generateIgnitionExports(): void {
  const projectRoot = process.cwd();
  const ignitionDeploymentsDir = path.join(projectRoot, "ignition", "deployments");
  const artifactsDir = path.join(projectRoot, "artifacts", "contracts");
  const outputDir = path.join(projectRoot, "src", "generated");

  // Ensure output directory exists
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const exports: GeneratedExports = {
    addresses: {},
    abis: {},
    networks: {},
  };

  console.log("🔍 Scanning for Ignition deployments...");

  // Read all chain deployment directories
  if (fs.existsSync(ignitionDeploymentsDir)) {
    const chainDirs = fs.readdirSync(ignitionDeploymentsDir, { withFileTypes: true })
      .filter(dirent => dirent.isDirectory() && dirent.name.startsWith("chain-"))
      .map(dirent => dirent.name);

    for (const chainDir of chainDirs) {
      const chainId = chainDir.replace("chain-", "");
      const deployedAddressesPath = path.join(ignitionDeploymentsDir, chainDir, "deployed_addresses.json");

      if (fs.existsSync(deployedAddressesPath)) {
        console.log(`📋 Processing ${chainDir} (chainId: ${chainId})`);

        const deployedAddresses: DeployedAddresses = JSON.parse(
          fs.readFileSync(deployedAddressesPath, "utf-8")
        );

        const networkName = getNetworkName(chainId);
        exports.networks[chainId] = networkName;

        // Transform deployment keys to contract names
        const networkAddresses: DeployedAddresses = {};
        for (const [deploymentKey, address] of Object.entries(deployedAddresses)) {
          const contractName = extractContractName(deploymentKey);
          networkAddresses[contractName] = address;
        }

        exports.addresses[networkName] = networkAddresses;
        console.log(`   ✅ Found ${Object.keys(networkAddresses).length} contracts`);
      }
    }
  }

  console.log("\n🔍 Scanning for contract ABIs...");

  // Collect ABIs from artifacts
  if (fs.existsSync(artifactsDir)) {
    const contractDirs = fs.readdirSync(artifactsDir, { withFileTypes: true })
      .filter(dirent => dirent.isDirectory())
      .map(dirent => dirent.name);

    for (const contractDir of contractDirs) {
      const contractDirPath = path.join(artifactsDir, contractDir);
      const jsonFiles = fs.readdirSync(contractDirPath)
        .filter(file => file.endsWith(".json") && !file.includes(".dbg."));

      for (const jsonFile of jsonFiles) {
        const jsonPath = path.join(contractDirPath, jsonFile);
        try {
          const artifact: ContractABI = JSON.parse(fs.readFileSync(jsonPath, "utf-8"));
          
          if (artifact.contractName && artifact.abi) {
            exports.abis[artifact.contractName] = artifact.abi;
            console.log(`   ✅ Loaded ABI for ${artifact.contractName}`);
          }
        } catch (error) {
          console.warn(`   ⚠️  Failed to parse ${jsonPath}: ${error}`);
        }
      }
    }
  }

  console.log("\n📝 Generating TypeScript exports...");

  // Generate addresses export
  const addressesContent = `// Auto-generated from Ignition deployments
// Do not edit this file directly

import type { Address } from "viem";

export interface ContractAddresses {
  [contractName: string]: Address;
}

export interface NetworkAddresses {
  [networkName: string]: ContractAddresses;
}

export const contractAddresses: NetworkAddresses = ${JSON.stringify(exports.addresses, null, 2)} as const;

export const networkChainIds: { [networkName: string]: string } = ${JSON.stringify(
    Object.fromEntries(Object.entries(exports.networks).map(([chainId, networkName]) => [networkName, chainId])),
    null,
    2
  )} as const;

export function getContractAddresses(networkName: string): ContractAddresses | undefined {
  return contractAddresses[networkName];
}

export function getContractAddress(networkName: string, contractName: string): Address | undefined {
  return contractAddresses[networkName]?.[contractName];
}

export function getAvailableNetworks(): string[] {
  return Object.keys(contractAddresses);
}
`;

  fs.writeFileSync(path.join(outputDir, "addresses.ts"), addressesContent);
  console.log("   ✅ Generated addresses.ts");

  // Generate ABIs export
  const abisContent = `// Auto-generated from contract artifacts
// Do not edit this file directly

export interface ContractABIs {
  [contractName: string]: any[];
}

export const contractABIs: ContractABIs = ${JSON.stringify(exports.abis, null, 2)} as const;

export function getContractABI(contractName: string): any[] | undefined {
  return contractABIs[contractName];
}

export function getAvailableContracts(): string[] {
  return Object.keys(contractABIs);
}
`;

  fs.writeFileSync(path.join(outputDir, "abis.ts"), abisContent);
  console.log("   ✅ Generated abis.ts");

  // Generate main index export
  const indexContent = `// Auto-generated contract exports
// Do not edit this file directly

export * from "./addresses";
export * from "./abis";
`;

  fs.writeFileSync(path.join(outputDir, "index.ts"), indexContent);
  console.log("   ✅ Generated index.ts");

  console.log("\n🎉 Ignition export generation complete!");
  console.log(`   📊 Networks: ${Object.keys(exports.addresses).length}`);
  console.log(`   📊 Contracts: ${Object.keys(exports.abis).length}`);
  console.log(`   📁 Output: ${outputDir}`);
}

// Run the script if called directly
if (import.meta.url === `file://${process.argv[1]}`) {
  generateIgnitionExports();
}

export { generateIgnitionExports };